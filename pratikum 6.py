# ===== Mahasiswa 1 =====
nama_mhs1 = "Zidan"
tugas_mhs1 = 80
ujian_mhs1 = 75

rata2_mhs1 = (tugas_mhs1 + ujian_mhs1) / 2
lulus_mhs1 = rata2_mhs1 >= 75

print("=" * 35)
print("REKAP NILAI MAHASISWA 1")
print("=" * 35)
print("Nama Mahasiswa :", nama_mhs1)
print("Nilai Tugas    :", tugas_mhs1)
print("Nilai Ujian    :", ujian_mhs1)
print("Rata-rata      :", rata2_mhs1)
print("Status Lulus   :", lulus_mhs1)
print("=" * 35)
print()

